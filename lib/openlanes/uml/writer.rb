# frozen_string_literal: true

require "fileutils"

module OpenLanes
  module Uml
    # Writes the map as `README.md` and every namespace's class diagram beside
    # it, each a Markdown file GitHub renders. A file this writer made earlier
    # for a namespace that no longer exists is removed; a file it did not
    # make carries no {MARKER} and is never touched.
    class Writer
      # The first line of every file written, and the proof it may be replaced.
      MARKER = "<!-- Generated by `openlanes uml`. Do not edit; run `just update-architecture`. -->"

      # @param model [OpenLanes::Uml::Model]
      # @param title [String] what the map's heading calls the project
      def initialize(model, title:)
        @model = model
        @title = title
      end

      # @return [Hash{String => String}] file name to contents
      def files
        pages = @model.namespace_names.to_h { [Writer.file_name(it), page(it, ClassDiagram.new(@model, it).render)] }
        { "README.md" => page("#{@title} namespaces", NamespaceMap.new(@model).render, index: pages.keys) }.merge(pages)
      end

      # @param dir [String]
      # @return [Array<String>] the paths written
      def write(dir)
        FileUtils.mkdir_p(dir)
        written = files.map { |name, body| File.join(dir, name).tap { File.write(it, body) } }
        (Dir.glob(File.join(dir, "*.md")) - written).select { generated?(it) }.each { File.delete(it) }
        written
      end

      # @param namespace [String]
      # @return [String] "openlanes-plans.md"
      def self.file_name(namespace) = "#{namespace.downcase.gsub(/[^a-z0-9]+/, "-").gsub(/\A-|-\z/, "")}.md"

      private

      # @return [String]
      def page(heading, mermaid, index: [])
        links = index.map { "- [#{it.delete_suffix(".md")}](#{it})" }
        [MARKER, "", "# #{heading}", "", "```mermaid", mermaid.chomp, "```", *(["", *links] unless links.empty?), ""].join("\n")
      end

      # @return [Boolean]
      def generated?(path) = File.open(path, &:gets)&.chomp == MARKER
    end
  end
end
